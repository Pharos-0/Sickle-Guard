"""Build and freeze plot-grouped train/val/test partitions.

    python src/make_splits.py

WHY GROUPED, AND WHY IT IS NOT A FORMALITY
------------------------------------------
131 plots contribute 319 field-seasons; every plot contributes at least two.
The data audit found that roughly 95 % of yield variance is BETWEEN plots
(SD of plot means 413 kg/acre against an overall SD of 433). A random
row-level split would therefore let a model memorise each plot's level and
score well without predicting anything. Splitting by plot forces the model to
predict the component that is actually hard.

STRATIFICATION
--------------
Plots are stratified by their mean yield tercile so that no partition is
handed systematically high or low fields, and the season mix is reported
afterwards rather than forced -- with 131 plots, stratifying on two axes at
once leaves cells too small to be meaningful.

The split is written to configs/splits.json and is not regenerated by any
later script. Downstream code reads the frozen file.
"""

from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

PROJ = Path(__file__).resolve().parents[1]
# dataset root; SICKLE_DATA_ROOT as in sickle-project/.env.example
TAB = Path(__import__("os").environ.get(
    "SICKLE_DATA_ROOT", "D:/FPD/sickledataset extracted")) / "sickle_dataset_tabular.csv"
OUT = PROJ / "configs" / "splits.json"
SEED = 20261011
FRAC = {"train": 0.61, "val": 0.19, "test": 0.20}


def load_yield_rows() -> list[dict]:
    rows = []
    with TAB.open(encoding="utf8") as fh:
        for r in csv.DictReader(fh):
            try:
                y = float(r["YIELD"])
                pid = float(r["PLOT_ID"])
            except (ValueError, KeyError):
                continue
            if y <= 0:
                continue
            rows.append({"uid": r["UNIQUE_ID"], "plot": pid, "yield": y,
                         "season": r["STANDARD_SEASON"], "year": r["YEAR"],
                         "area": float(r["AREA"]) if r["AREA"].strip() else None,
                         "variety": r["VARIETY"], "split_released": r["SPLIT"]})
    return rows


def main() -> int:
    rows = load_yield_rows()
    by_plot = defaultdict(list)
    for r in rows:
        by_plot[r["plot"]].append(r)
    plots = sorted(by_plot)
    print(f"{len(rows)} yield-labelled field-seasons from {len(plots)} plots")

    means = {p: float(np.mean([r["yield"] for r in by_plot[p]])) for p in plots}
    q = np.quantile(list(means.values()), [1 / 3, 2 / 3])
    tercile = {p: int(np.searchsorted(q, means[p])) for p in plots}

    rng = np.random.default_rng(SEED)
    assign: dict[float, str] = {}
    for t in (0, 1, 2):
        grp = [p for p in plots if tercile[p] == t]
        rng.shuffle(grp)
        n = len(grp)
        n_tr = int(round(FRAC["train"] * n))
        n_va = int(round(FRAC["val"] * n))
        for p in grp[:n_tr]:
            assign[p] = "train"
        for p in grp[n_tr:n_tr + n_va]:
            assign[p] = "val"
        for p in grp[n_tr + n_va:]:
            assign[p] = "test"

    split_plots = {s: sorted(p for p in plots if assign[p] == s)
                   for s in ("train", "val", "test")}
    split_rows = {s: [r["uid"] for r in rows if assign[r["plot"]] == s]
                  for s in ("train", "val", "test")}

    # ---- the checks that make this trustworthy -------------------------
    allp = [set(split_plots[s]) for s in ("train", "val", "test")]
    assert not (allp[0] & allp[1]), "train/val share a plot"
    assert not (allp[0] & allp[2]), "train/test share a plot"
    assert not (allp[1] & allp[2]), "val/test share a plot"
    assert sum(len(v) for v in split_plots.values()) == len(plots)
    assert sum(len(v) for v in split_rows.values()) == len(rows)
    uid_all = [u for v in split_rows.values() for u in v]
    assert len(uid_all) == len(set(uid_all)), "a field-season is in two splits"

    print(f"\n{'split':6s}{'plots':>7s}{'field-seasons':>15s}"
          f"{'mean yield':>12s}{'SD':>8s}")
    stats = {}
    for s in ("train", "val", "test"):
        ys = [r["yield"] for r in rows if assign[r["plot"]] == s]
        stats[s] = {"n_plots": len(split_plots[s]), "n_rows": len(ys),
                    "mean_yield": float(np.mean(ys)),
                    "sd_yield": float(np.std(ys))}
        print(f"{s:6s}{len(split_plots[s]):>7d}{len(ys):>15d}"
              f"{np.mean(ys):>12.1f}{np.std(ys):>8.1f}")

    print("\nseason mix per split (not forced; reported)")
    for s in ("train", "val", "test"):
        c = Counter(r["season"] for r in rows if assign[r["plot"]] == s)
        tot = sum(c.values())
        print(f"  {s:6s} " + "  ".join(
            f"{k} {v}({100*v/tot:.0f}%)" for k, v in c.most_common()))

    blob = {
        "seed": SEED, "fractions": FRAC,
        "grouping_key": "PLOT_ID",
        "stratified_by": "plot-mean yield tercile",
        "n_plots": len(plots), "n_field_seasons": len(rows),
        "stats": stats,
        "plots": {s: split_plots[s] for s in split_plots},
        "field_seasons": split_rows,
        "note": ("Frozen. Downstream scripts read this file and never "
                 "regenerate it. No plot appears in more than one split; "
                 "asserted at build time and re-asserted by "
                 "tests/test_splits.py."),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(blob, indent=2), encoding="utf8")
    print(f"\nwrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
